package main

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"
)

const goHeader = "// Code generated by protocolgen from protocol/idl.json; DO NOT EDIT.\n\npackage protocol\n"

func goTypes(d *idl) ([]byte, error) {
	var body bytes.Buffer
	fmt.Fprintf(&body, "\nconst Version = %q\n", d.version)
	marshal := false
	for _, name := range d.typeNames() {
		s := d.named[name]
		if s.Enum != nil {
			writeGoEnum(&body, name, s)
			continue
		}
		writeGoStruct(&body, name, s)
		marshal = writeGoMarshal(&body, name, s) || marshal
	}
	body.WriteString("\ntype ErrorResponse struct {\nError ErrorInfo `json:\"error\"`\n}\n")
	writeGoMessageTypes(&body, d)
	writeGoCloseCodes(&body, d.WS.CloseCodes)
	writeGoRoutes(&body, d.HTTP)
	writeGoRoomRoutes(&body, d)
	writeGoHTTPStatus(&body, d)

	var b bytes.Buffer
	b.WriteString(goHeader)
	if marshal {
		b.WriteString("\nimport \"encoding/json\"\n")
	}
	b.Write(body.Bytes())
	return format.Source(b.Bytes())
}

func writeGoEnum(b *bytes.Buffer, name string, s *schema) {
	fmt.Fprintf(b, "\ntype %s string\n\nconst (\n", name)
	for _, v := range s.Enum {
		fmt.Fprintf(b, "%s%s %s = %q\n", name, pascal(v), name, v)
	}
	b.WriteString(")\n")
}

func writeGoStruct(b *bytes.Buffer, name string, s *schema) {
	if len(s.Properties) == 0 {
		fmt.Fprintf(b, "\ntype %s struct{}\n", name)
		return
	}
	fmt.Fprintf(b, "\ntype %s struct {\n", name)
	for _, p := range slices.Sorted(maps.Keys(s.Properties)) {
		required := slices.Contains(s.Required, p)
		tag := p
		if !required {
			tag += ",omitempty"
		}
		fmt.Fprintf(b, "%s %s `json:%q`\n", pascal(p), goFieldType(s.Properties[p], required), tag)
	}
	b.WriteString("}\n")
}

func goFieldType(s *schema, required bool) string {
	switch {
	case s.AnyOf != nil:
		return "*" + goValueType(s.AnyOf[0])
	case s.Type == "array":
		return "[]" + goValueType(s.Items)
	case !required:
		return "*" + goValueType(s)
	default:
		return goValueType(s)
	}
}

func goValueType(s *schema) string {
	if s.Ref != "" {
		return refName(s.Ref)
	}
	return map[string]string{"string": "string", "integer": "int64", "number": "float64", "boolean": "bool"}[s.Type]
}

func writeGoMarshal(b *bytes.Buffer, name string, s *schema) bool {
	var arrays []string
	for _, p := range slices.Sorted(maps.Keys(s.Properties)) {
		if s.Properties[p].Type == "array" {
			arrays = append(arrays, p)
		}
	}
	if len(arrays) == 0 {
		return false
	}
	fmt.Fprintf(b, "\nfunc (v %s) MarshalJSON() ([]byte, error) {\ntype plain %s\n", name, name)
	for _, p := range arrays {
		fmt.Fprintf(b, "if v.%s == nil {\nv.%s = []%s{}\n}\n", pascal(p), pascal(p), goValueType(s.Properties[p].Items))
	}
	b.WriteString("return json.Marshal(plain(v))\n}\n")
	return true
}

func writeGoMessageTypes(b *bytes.Buffer, d *idl) {
	b.WriteString("\nconst (\n")
	for _, m := range slices.Concat(d.WS.Requests, d.Requests) {
		fmt.Fprintf(b, "Request%s = %q\n", pascal(m.Type), m.Type)
	}
	b.WriteString(")\n\nconst (\n")
	for _, e := range slices.Concat(d.WS.Events, d.Events) {
		fmt.Fprintf(b, "Event%s = %q\n", pascal(e.Type), e.Type)
	}
	b.WriteString(")\n")
}

func writeGoCloseCodes(b *bytes.Buffer, codes []*closeCode) {
	if len(codes) == 0 {
		return
	}
	b.WriteString("\nconst (\n")
	for _, c := range codes {
		fmt.Fprintf(b, "Close%s = %d\n", pascal(c.Name), c.Code)
	}
	b.WriteString(")\n")
}

func writeGoRoutes(b *bytes.Buffer, endpoints []*endpoint) {
	if len(endpoints) == 0 {
		return
	}
	b.WriteString("\nvar (\n")
	for _, e := range endpoints {
		fmt.Fprintf(b, "Route%s = Route{Pattern: %q, Auth: Auth%s, Status: %d%s}\n", pascal(e.Name), e.Method+" "+e.Path, pascal(e.Auth), e.status(), goLocation(e.Location))
	}
	b.WriteString(")\n")
}

func goLocation(location bool) string {
	if location {
		return ", Location: true"
	}
	return ""
}

func writeGoRoomRoutes(b *bytes.Buffer, d *idl) {
	if len(d.Requests) == 0 {
		return
	}
	b.WriteString("\nvar RoomRoutes = []RoomRoute{\n")
	for _, m := range d.Requests {
		h := m.HTTP
		fmt.Fprintf(b, "{Route: Route{Pattern: %q, Auth: AuthTicket, Status: %d%s}, Type: Request%s", h.Method+" "+h.Path, h.status(), goLocation(h.Location), pascal(m.Type))
		params := pathParams(h.Path)
		if len(params) > 0 {
			fmt.Fprintf(b, ", params: []string{%s}", goStrings(params))
		}
		if h.Method != "GET" && h.Method != "DELETE" {
			b.WriteString(", body: true")
		} else if query := d.queryKinds(m.Request, params); len(query) > 0 {
			fmt.Fprintf(b, ", query: map[string]queryKind{%s}", strings.Join(query, ", "))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
}

func (d *idl) queryKinds(s *schema, params []string) []string {
	var kinds []string
	for _, name := range slices.Sorted(maps.Keys(s.Properties)) {
		if slices.Contains(params, name) {
			continue
		}
		kind := "queryString"
		if d.jsonType(s.Properties[name]) == "integer" {
			kind = "queryInteger"
		}
		kinds = append(kinds, fmt.Sprintf("%q: %s", name, kind))
	}
	return kinds
}

func writeGoHTTPStatus(b *bytes.Buffer, d *idl) {
	for _, name := range d.typeNames() {
		s := d.named[name]
		if s.HTTPStatus == nil {
			continue
		}
		table := lowerFirst(name) + "HTTPStatus"
		fmt.Fprintf(b, "\nvar %s = map[%s]int{\n", table, name)
		for _, v := range s.Enum {
			if status, ok := s.HTTPStatus[v]; ok {
				fmt.Fprintf(b, "%s%s: %d,\n", name, pascal(v), status)
			}
		}
		fmt.Fprintf(b, "}\n\n// IDL 没有为某个取值指定 HTTP 状态码时返回 0。\nfunc (v %s) HTTPStatus() int {\nreturn %s[v]\n}\n", name, table)
	}
}

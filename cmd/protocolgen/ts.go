const tsHeader = "// Code generated by protocolgen from protocol/idl.json; DO NOT EDIT.\n"

func tsProtocol(d *idl) []byte {
	httpTypes := d.httpTypeNames()
	var b bytes.Buffer
	b.WriteString(tsHeader)
	fmt.Fprintf(&b, "\nexport const PROTOCOL_VERSION = '%s'\n", d.version)
	for _, name := range d.typeNames() {
		if !httpTypes[name] {
			writeTSType(&b, name, d.named[name])
		}
	}

	requests := slices.Concat(d.WS.Requests, d.Requests)
	writeTSMap(&b, "RequestDataMap", requests, func(m *message) (string, *schema) { return m.Type, m.Request })
	writeTSMap(&b, "ResponseDataMap", requests, func(m *message) (string, *schema) { return m.Type, m.Response })
	writeTSMap(&b, "ConnectionEventDataMap", d.WS.Events, func(e *event) (string, *schema) { return e.Type, e.Data })
	writeTSMap(&b, "RoomEventDataMap", d.Events, func(e *event) (string, *schema) { return e.Type, e.Data })
	b.WriteString(tsEnvelopes)

	b.WriteString("\nexport const CloseCode = {\n")
	for _, c := range d.WS.CloseCodes {
		fmt.Fprintf(&b, "  %s: %d,\n", c.Name, c.Code)
	}
	b.WriteString("} as const\n")

	b.WriteString("\nexport type Send = <T extends RequestType>(type: T, data: RequestDataMap[T]) => Promise<ResponseDataMap[T]>\n")
	b.WriteString("\nexport function roomRequests(send: Send) {\n  return {\n")
	for _, m := range d.Requests {
		if len(m.Request.Properties) == 0 {
			fmt.Fprintf(&b, "    %s: () => send('%s', {}),\n", camel(m.Type), m.Type)
		} else {
			fmt.Fprintf(&b, "    %s: (data: %s) => send('%s', data),\n", camel(m.Type), m.Request.name, m.Type)
		}
	}
	b.WriteString("  }\n}\n")
	if names := d.urlDefs(); len(names) > 0 {
		b.WriteString(tsURLRule)
		for _, name := range names {
			writeTSValidator(&b, name, d.Defs[name])
		}
	}
	return b.Bytes()
}

// 与 protocol/decode.go 中的 validURL 是同一套规则，两边由 protocol/testdata 中共用的用例检查。
const tsURLRule = `
function validURL(value: string): boolean {
  if (/[\u0000-\u0020\u007F\\]/.test(value))
    return false
  const scheme = /^https?:\/\//i.exec(value)
  if (scheme === null)
    return false
  const rest = value.slice(scheme[0].length)
  const end = rest.search(/[/?#]/)
  const authority = end < 0 ? rest : rest.slice(0, end)
  const tail = end < 0 ? '' : rest.slice(end)
  let host = authority
  let port = ''
  if (authority.startsWith('[')) {
    const close = authority.indexOf(']') + 1
    host = authority.slice(0, close)
    if (close === 0 || !/^\[[0-9A-Fa-f:.]+\]$/.test(host))
      return false
    const after = authority.slice(close)
    if (after !== '') {
      if (!after.startsWith(':'))
        return false
      port = after.slice(1)
    }
  }
  else {
    const colon = authority.indexOf(':')
    if (colon >= 0) {
      host = authority.slice(0, colon)
      port = authority.slice(colon + 1)
    }
    if (!/^[\w.~\u0080-\u{10FFFF}-]+$/u.test(host))
      return false
    const labels = host.replace(/\.$/, '').split('.')
    if (/^(?:\d+|0x[0-9a-f]*)$/i.test(labels[labels.length - 1]) && !/^(?:(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)\.){3}(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)$/.test(host))
      return false
  }
  if (!/^\d*$/.test(port) || Number(port) > 65535)
    return false
  const hash = tail.indexOf('#')
  const path = (hash < 0 ? tail : tail.slice(0, hash)).split('?')[0]
  const fragment = hash < 0 ? '' : tail.slice(hash + 1)
  const badEscape = /%(?![0-9A-Fa-f]{2})/
  if (badEscape.test(path) || badEscape.test(fragment))
    return false
  try {
    return new URL(value).hostname !== ''
  }
  catch {
    return false
  }
}
`

func writeTSValidator(b *bytes.Buffer, name string, s *schema) {
	var checks []string
	if s.MinLength != nil {
		checks = append(checks, fmt.Sprintf("[...value].length >= %d", *s.MinLength))
	}
	if s.MaxLength != nil {
		checks = append(checks, fmt.Sprintf("[...value].length <= %d", *s.MaxLength))
	}
	if s.MaxBytes != nil {
		checks = append(checks, fmt.Sprintf("new TextEncoder().encode(value).length <= %d", *s.MaxBytes))
	}
	checks = append(checks, "validURL(value)")
	fmt.Fprintf(b, "\nexport function is%s(value: string): boolean {\n  return %s\n}\n", name, strings.Join(checks, " && "))
}


func tsHTTP(d *idl) []byte {
	httpTypes := d.httpTypeNames()
	var body bytes.Buffer
	imports := map[string]bool{"ErrorInfo": true}
	for _, name := range slices.Sorted(maps.Keys(httpTypes)) {
		s := d.named[name]
		writeTSType(&body, name, s)
		for _, p := range s.Properties {
			if ref := tsRef(p); ref != "" {
				imports[ref] = true
			}
		}
	}
	body.WriteString(tsHTTPRuntime)
	body.WriteString("\nexport function httpClient(send: HttpSend) {\n  return {\n")
	for _, e := range d.HTTP {
		response := "void"
		if e.Response != nil {
			response = e.Response.dataType()
			if e.Response.Ref != "" {
				imports[response] = true
			}
		}
		var params []string
		path := e.Path
		for _, p := range pathParams(e.Path) {
			params = append(params, p+": string")
			path = strings.Replace(path, "{"+p+"}", "${encodeURIComponent("+p+")}", 1)
		}
		quoted := "'" + path + "'"
		if strings.Contains(path, "${") {
			quoted = "`" + path + "`"
		}
		requestBody := ""
		if e.Request != nil {
			if len(e.Request.Properties) == 0 {
				requestBody = ", body: {}"
			} else {
				params = append(params, "body: "+e.Request.name)
				requestBody = ", body"
			}
		}
		fmt.Fprintf(&body, "    %s: (%s) => send<%s>({ method: '%s', path: %s, auth: '%s'%s }),\n", e.Name, strings.Join(params, ", "), response, e.Method, quoted, e.Auth, requestBody)
	}
	body.WriteString("  }\n}\n")

	var b bytes.Buffer
	b.WriteString(tsHeader)
	fmt.Fprintf(&b, "\nimport type { %s } from '../realtime/protocol.gen'\n", strings.Join(slices.Sorted(maps.Keys(imports)), ", "))
	b.Write(body.Bytes())
	return b.Bytes()
}

const tsHTTPRuntime = `
export interface ErrorResponse {
  error: ErrorInfo
}

export type Auth = 'none' | 'member' | 'admin'

export interface HttpRequest {
  method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'
  path: string
  auth: Auth
  body?: unknown
}

export type HttpSend = <T>(request: HttpRequest) => Promise<T>
`

func (d *idl) httpTypeNames() map[string]bool {
	names := map[string]bool{}
	for _, e := range d.HTTP {
		for _, s := range []*schema{e.Request, e.Response} {
			if s != nil && s.Ref == "" {
				names[s.name] = true
			}
		}
	}
	return names
}

func writeTSMap[T any](b *bytes.Buffer, name string, items []T, entry func(T) (string, *schema)) {
	fmt.Fprintf(b, "\nexport interface %s {\n", name)
	for _, item := range items {
		key, s := entry(item)
		fmt.Fprintf(b, "  '%s': %s\n", key, s.dataType())
	}
	b.WriteString("}\n")
}

func writeTSType(b *bytes.Buffer, name string, s *schema) {
	switch {
	case s.Enum != nil:
		values := make([]string, len(s.Enum))
		for i, v := range s.Enum {
			values[i] = "'" + v + "'"
		}
		fmt.Fprintf(b, "\nexport type %s = %s\n", name, strings.Join(values, " | "))
	case len(s.Properties) == 0:
		fmt.Fprintf(b, "\nexport type %s = Record<string, never>\n", name)
	case s.OneOf != nil:
		optional := optionalFields(s.OneOf[0])
		alternatives := make([]string, len(s.OneOf))
		for i, alt := range s.OneOf {
			fields := make([]string, 0, len(alt.Required)+len(optional))
			for _, f := range alt.Required {
				fields = append(fields, f+": "+tsFieldType(s.Properties[f]))
			}
			for _, f := range optional {
				fields = append(fields, f+"?: "+tsFieldType(s.Properties[f]))
			}
			alternatives[i] = "{ " + strings.Join(fields, ", ") + " }"
		}
		fmt.Fprintf(b, "\nexport type %s = %s\n", name, strings.Join(alternatives, " | "))
	default:
		fmt.Fprintf(b, "\nexport interface %s {\n", name)
		for _, p := range slices.Sorted(maps.Keys(s.Properties)) {
			optional := ""
			if !slices.Contains(s.Required, p) {
				optional = "?"
			}
			fmt.Fprintf(b, "  %s%s: %s\n", p, optional, tsFieldType(s.Properties[p]))
		}
		b.WriteString("}\n")
	}
}

func tsFieldType(s *schema) string {
	switch {
	case s.AnyOf != nil:
		return tsValueType(s.AnyOf[0]) + " | null"
	case s.Type == "array":
		return tsValueType(s.Items) + "[]"
	default:
		return tsValueType(s)
	}
}

func tsValueType(s *schema) string {
	if s.Ref != "" {
		return refName(s.Ref)
	}
	return map[string]string{"string": "string", "integer": "number", "number": "number", "boolean": "boolean"}[s.Type]
}

func tsRef(s *schema) string {
	switch {
	case s.AnyOf != nil:
		return refName(s.AnyOf[0].Ref)
	case s.Type == "array":
		return refName(s.Items.Ref)
	default:
		return refName(s.Ref)
	}
}
